-- 1. Total sales, profit and quantity
SELECT SUM(Amount) AS Total_Sales,
       SUM(Profit) AS Total_Profit,
       SUM(Quantity) AS Total_Quantity
FROM Details;

-- 2. Sales and profit by category
SELECT Category,
       SUM(Amount) AS Sales,
       SUM(Profit) AS Profit,
       SUM(Quantity) AS Quantity
FROM Details
GROUP BY Category
ORDER BY Sales DESC;

-- 3. Sales and profit by sub-category
SELECT `Sub_Category`,
       SUM(Amount) AS Sales,
       SUM(Profit) AS Profit
FROM Details
GROUP BY `Sub_Category`
ORDER BY Sales DESC;

-- 4. Top 10 customers by sales
SELECT o.CustomerName,
       SUM(d.Amount) AS Sales,
       SUM(d.Profit) AS Profit
FROM Orders o
JOIN Details d ON o.Order_ID = d.Order_ID
GROUP BY o.CustomerName
ORDER BY Sales DESC
LIMIT 10;

-- 5. State-wise sales and profit
SELECT o.State,
       SUM(d.Amount) AS Sales,
       SUM(d.Profit) AS Profit
FROM Orders o
JOIN Details d ON o.Order_ID = d.Order_ID
GROUP BY o.State
ORDER BY Sales DESC;

-- 6. City-wise sales
SELECT o.City,
       SUM(d.Amount) AS Sales
FROM Orders o
JOIN Details d ON o.Order_ID = d.Order_ID
GROUP BY o.City
ORDER BY Sales DESC
LIMIT 15;

-- 7. Payment mode performance
SELECT PaymentMode,
       COUNT(*) AS Transactions,
       SUM(Amount) AS Sales,
       SUM(Profit) AS Profit
FROM Details
GROUP BY PaymentMode
ORDER BY Sales DESC;

-- 8. Monthly sales and profit
SELECT DATE_FORMAT(o.Order_Date, '%Y-%m') AS Month,
       SUM(d.Amount) AS Sales,
       SUM(d.Profit) AS Profit
FROM Orders o
JOIN Details d ON o.Order_ID = d.Order_ID
GROUP BY DATE_FORMAT(o.Order_Date, '%Y-%m')
ORDER BY Month;

-- 9. Most profitable sub-categories
SELECT `Sub_Category`,
       SUM(Profit) AS Profit
FROM Details
GROUP BY `Sub_Category`
ORDER BY Profit DESC
LIMIT 10;

-- 10. Loss-making sub-categories
SELECT `Sub_Category`,
       SUM(Profit) AS Profit
FROM Details
GROUP BY `Sub_Category`
HAVING SUM(Profit) < 0
ORDER BY Profit ASC;

-- 11. Average order value
SELECT ROUND(SUM(d.Amount) / COUNT(DISTINCT d.Order_ID), 2) AS Average_Order_Value
FROM Details d;

-- 12. Top 10 orders by profit
SELECT o.Order_ID, o.CustomerName,
       SUM(d.Amount) AS Sales,
       SUM(d.Profit) AS Profit
FROM Orders o
JOIN Details d ON o.Order_ID = d.Order_ID
GROUP BY o.Order_ID, o.CustomerName
ORDER BY Profit DESC
LIMIT 10;

-- 13. Category + payment mode analysis
SELECT Category, PaymentMode,
       SUM(Amount) AS Sales,
       SUM(Profit) AS Profit
FROM Details
GROUP BY Category, PaymentMode
ORDER BY Sales DESC;

